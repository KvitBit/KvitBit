import { APP_BASE } from "./manifest";

/** Every cache this worker owns starts with this; activate drops the others. */
export const CACHE_PREFIX = "kvitbit-app-";

export type ServiceWorkerOptions = {
  /** Distinguishes one export from the next; changes the cache name. */
  readonly version: string;
  /** Hashed `/app/_expo/static/**` URLs to precache on install. */
  readonly precache: ReadonlyArray<string>;
};

/**
 * Source of `dist/sw.js`. Hashed static bundles are cache-first; navigations
 * are network-first with the last good shell as the offline answer. `/api/**`,
 * cross-origin and non-GET requests never reach the cache.
 */
export const serviceWorkerSource = ({
  version,
  precache,
}: ServiceWorkerOptions): string => `// Generated by apps/mobile/scripts/build-pwa.ts. Do not edit.
const CACHE = ${JSON.stringify(`${CACHE_PREFIX}${version}`)};
const PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const BASE = ${JSON.stringify(APP_BASE)};
const STATIC = ${JSON.stringify(`${APP_BASE}_expo/static/`)};
const SHELL = ${JSON.stringify(`${APP_BASE}index.html`)};
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) =>
        Promise.all([
          cache.addAll(PRECACHE),
          fetch(new Request(BASE, { cache: "reload" })).then((response) =>
            response.ok ? cache.put(SHELL, response) : undefined,
          ),
        ]),
      )
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys.filter((key) => key.startsWith(PREFIX) && key !== CACHE).map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

const cacheFirst = async (request) => {
  const cache = await caches.open(CACHE);
  const hit = await cache.match(request);
  if (hit) return hit;
  const response = await fetch(request);
  if (response.ok) await cache.put(request, response.clone());
  return response;
};

const networkFirstShell = async (request) => {
  const cache = await caches.open(CACHE);
  try {
    const response = await fetch(request);
    const type = response.headers.get("content-type") || "";
    if (response.ok && type.includes("text/html")) await cache.put(SHELL, response.clone());
    return response;
  } catch (error) {
    const shell = await cache.match(SHELL);
    if (shell) return shell;
    throw error;
  }
};

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (!url.pathname.startsWith(BASE)) return;
  if (url.pathname.startsWith(STATIC)) {
    event.respondWith(cacheFirst(request));
    return;
  }
  if (request.mode === "navigate" || url.pathname === BASE || url.pathname === SHELL) {
    event.respondWith(networkFirstShell(request));
  }
});
`;
