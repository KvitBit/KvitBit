import { APP_BASE } from "./manifest";

/** Every cache this worker owns starts with this; activate drops the others. */
const LEGACY_CACHE_PREFIX = "kvitbit-app-";
export const CACHE_PREFIX = `${LEGACY_CACHE_PREFIX}v2-`;

export type ServiceWorkerOptions = {
  /** Distinguishes one export from the next; changes the cache name. */
  readonly version: string;
  /** Hashed `/app/_expo/static/**` URLs to precache on install. */
  readonly precache: ReadonlyArray<string>;
  readonly integrity: Readonly<Record<string, string>>;
};

/**
 * Source of `dist/sw.js`. Hashed static bundles are cache-first; navigations
 * are network-first with the known public shell as the offline fallback.
 * `/api/**`, `/mcp/**`, cross-origin, non-GET, `private`, `no-store`, and
 * `Set-Cookie` responses are never written to any cache.
 */
export const serviceWorkerSource = ({
  version,
  precache,
  integrity,
}: ServiceWorkerOptions): string => `// Generated by apps/mobile/scripts/build-pwa.ts. Do not edit.
const CACHE = ${JSON.stringify(`${CACHE_PREFIX}${version}`)};
const PREFIX = ${JSON.stringify(LEGACY_CACHE_PREFIX)};
const BASE = ${JSON.stringify(APP_BASE)};
const SHELL = ${JSON.stringify(`${APP_BASE}index.html`)};
const PRECACHE = ${JSON.stringify(precache)};
const INTEGRITY = ${JSON.stringify(integrity)};
const NO_CACHE_DIRECTIVE = /(?:^|,)\\s*(?:private|no-store)\\b/i;
const PRIVATE_VARY = /(?:^|,)\\s*(?:cookie|authorization|\\*)(?:\\s*,|\\s*$)/i;

const fetchPublicArtifact = async (path) => {
  const url = new URL(path, self.location.origin).href;
  return fetch(new Request(url, {
    cache: "reload",
    credentials: "omit",
    redirect: "error",
    integrity: INTEGRITY[path],
  }));
};

const storePublicArtifact = async (cache, path, response) => {
  if (response.status !== 200 || response.url !== new URL(path, self.location.origin).href) return;
  if (response.type !== "basic" && response.type !== "default") return;
  const headers = response.headers;
  if (NO_CACHE_DIRECTIVE.test(headers.get("cache-control") || "")) return;
  if (PRIVATE_VARY.test(headers.get("vary") || "")) return;
  if (headers.has("set-cookie") || headers.has("set-cookie2")) return;
  if (path === SHELL && !(headers.get("content-type") || "").toLowerCase().startsWith("text/html")) return;
  // Browsers filter Set-Cookie from script-visible headers. Cache only the SRI-checked,
  // anonymous artifact and its filtered headers, so offline replays cannot carry cookies.
  const storedHeaders = new Headers(headers);
  storedHeaders.delete("content-encoding");
  storedHeaders.delete("content-length");
  await cache.put(path, new Response(response.clone().body, { headers: storedHeaders }));
};

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await Promise.all([SHELL, ...PRECACHE].map(async (path) => {
      await storePublicArtifact(cache, path, await fetchPublicArtifact(path));
    }));
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys.filter((key) => key.startsWith(PREFIX) && key !== CACHE).map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

const cacheFirst = async (path, request) => {
  const cache = await caches.open(CACHE);
  const hit = await cache.match(path);
  if (hit) return hit;
  try {
    const response = await fetchPublicArtifact(path);
    await storePublicArtifact(cache, path, response);
    return response;
  } catch {
    // A previous export may still be open during deployment.
    return fetch(request);
  }
};

const networkFirstShell = async (request) => {
  try {
    return await fetch(request);
  } catch (error) {
    const shell = await (await caches.open(CACHE)).match(SHELL);
    if (shell) return shell;
    throw error;
  }
};

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || request.headers.has("authorization")) return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE)) return;
  if (request.mode === "navigate" || url.pathname === BASE || url.pathname === SHELL) {
    event.respondWith(networkFirstShell(request));
    return;
  }
  if (url.search === "" && Object.hasOwn(INTEGRITY, url.pathname)) {
    event.respondWith(cacheFirst(url.pathname, request));
  }
});
`;
