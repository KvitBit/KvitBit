/**
 * Regenerates src/theme/default-theme.data.ts from the graphite_atelier preset.
 * Run: bun packages/ui-port/test/theme/generate-default-theme.ts
 */
import * as Exit from "effect/Exit";
import * as Schema from "effect/Schema";
import { resolvePreset } from "../../src/theme/resolve";

const encodeJson = Schema.encodeUnknownExit(Schema.fromJsonString(Schema.Unknown, { space: 2 }));
const theme = resolvePreset("graphite_atelier");
const json = encodeJson(theme);
if (Exit.isFailure(json)) throw new Error("Could not encode default theme", { cause: json.cause });
const body = `/**
 * GENERATED by test/theme/generate-default-theme.ts from the graphite_atelier preset; do not
 * edit. test/theme/default-theme.test.ts fails when it drifts from the resolver.
 */
import type { ResolvedTheme } from "@kvitbit/api-contract";

export const DEFAULT_THEME_DATA: ResolvedTheme = ${json.value};
`;
await Bun.write(new URL("../../src/theme/default-theme.data.ts", import.meta.url), body);
